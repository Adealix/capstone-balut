"""Proof that offline data stays marked and a pending registration syncs once.
Uses only the demonstration records generated by emulator_smoke.py.
"""
from emulator_workflow import *
import uuid
def post(path,body,auth):
    req=urllib.request.Request('http://127.0.0.1:8787'+path,data=json.dumps(body).encode(),headers={'Content-Type':'application/json','Authorization':'Bearer '+auth,'X-Request-ID':str(uuid.uuid4())})
    return json.loads(urllib.request.urlopen(req,timeout=15).read())
def run():
    auth=token();s=api('/snapshot',token=auth);assert s['mode']=='simulation'
    # Release one demonstration C1 position as fixture preparation, not a production action.
    sample=next(b for b in s['batches'] if b['name']=='Morning collection')
    for g in s['groups']:
        if g['batch_id']==sample['id'] and g['quantity']>0:post('/groups/'+g['id']+'/complete',{'quantity':g['quantity'],'outcome':'Removed','version':g['version']},auth)
    shell('am','force-stop','com.capstone.balut');shell('am','start','-n','com.capstone.balut/.MainActivity');time.sleep(3)
    subprocess.run(['powershell','-ExecutionPolicy','Bypass','-File',str(ROOT/'tools/Stop-Backend.ps1')],check=True,capture_output=True)
    tap('Dashboard tab');tap('Refresh device status');time.sleep(3);assert_text('Offline')
    tap('Home tab');tap('Register a batch');fill_field('Batch name','Offline test collection');fill_field('Egg source / supplier','QA offline');fill_field('Number of eggs','3');tap('Initial tray position',True);tap('C1-2');tap('Save batch',True);time.sleep(2);tap('Keep pending');time.sleep(1);assert_text('pending');screenshot('10-offline-pending')
    subprocess.run(['powershell','-ExecutionPolicy','Bypass','-File',str(ROOT/'tools/Start-Backend.ps1')],check=True)
    time.sleep(3);tap('Dashboard tab');tap('Refresh device status');time.sleep(4)
    records=[b for b in fresh()['batches'] if b['name']=='Offline test collection'];assert len(records)==1
    assert records[0]['total']==3
    tap('Batches tab');fill_field('Search name, batch ID or source','Offline test collection');assert_text('Offline test collection');screenshot('11-offline-synchronized')
    result={'offline_banner_verified':True,'pending_registration_saved':True,'automatic_sync_after_reconnection':True,'exactly_one_server_record':True,'registered_quantity':3,'mode':'simulation'}
    (EVIDENCE/'emulator-offline.json').write_text(json.dumps(result,indent=2));print(json.dumps(result,indent=2));tap('Home tab')
if __name__=='__main__':run()
